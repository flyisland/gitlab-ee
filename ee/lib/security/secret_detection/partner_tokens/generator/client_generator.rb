# frozen_string_literal: true

module Security
  module SecretDetection
    module PartnerTokens
      module Generator
        # Turns a reviewed VendorDefinition into ADR-006-conformant Ruby source: a
        # verifier client and its spec. The generated client always:
        #   - maps only explicitly-declared HTTP codes,
        #   - falls through to :unknown (never :inactive),
        #   - raises RateLimitError / NetworkError for the codes the vendor definition
        #     marks as such.
        #
        # The output is deterministic and reviewable, so a human still approves
        # every generated verifier before it ships. The AI's job is only to
        # produce the *data* (VendorDefinition) from the vendor docs.
        class ClientGenerator
          RATE_LIMIT = :rate_limit
          NETWORK_ERROR = :network_error

          CLIENT_DIR = 'ee/lib/security/secret_detection/partner_tokens'
          SPEC_DIR = 'ee/spec/lib/security/secret_detection/partner_tokens'

          def initialize(vendor_definition)
            @definition = vendor_definition
          end

          def client_source
            <<~RUBY
              # frozen_string_literal: true

              module Security
                module SecretDetection
                  module PartnerTokens
                    # Auto-generated by ClientGenerator from a reviewed VendorDefinition.
                    # #{@definition.doc_url.present? ? "Vendor docs: #{@definition.doc_url}" : 'The definition provided no vendor doc URL.'}
                    # Regenerate rather than hand-editing; keep the VendorDefinition as the source of truth.
                    class #{@definition.class_name} < BaseClient
              #{class_body_source.indent(8)}
                    end
                  end
                end
              end
            RUBY
          end

          # Just the constants + method definitions that live inside the class
          # body. Shared by client_source and by tests that eval the body into an
          # anonymous subclass of BaseClient.
          def class_body_source
            <<~RUBY.chomp
              API_ENDPOINT = #{@definition.endpoint.inspect}

              private

              def partner_name
                #{@definition.partner_name.downcase.inspect}
              end

              def verify_partner_token(token_value)
                response = make_request(
                  API_ENDPOINT,
                  method: :#{@definition.http_method},
                  headers: #{headers_literal}
                )
                analyze_response(response)
              end

              def analyze_response(response)
                case response.code.to_i
                #{when_branches}
                else
                  # unknown-never-inactive: unmapped codes are never treated as dead tokens.
                  token_response(:unknown)
                end
              end
            RUBY
          end

          def client_path
            "#{CLIENT_DIR}/#{@definition.class_name.underscore}.rb"
          end

          def spec_path
            "#{SPEC_DIR}/#{@definition.class_name.underscore}_spec.rb"
          end

          def registry_entry
            <<~RUBY.chomp
              #{@definition.token_type.inspect} => {
                client_class: ::Security::SecretDetection::PartnerTokens::#{@definition.class_name},
                rate_limit_key: :#{@definition.rate_limit_key},
                enabled: true,
                enabled_targets: [Scanners::GSS].freeze
              }.freeze
            RUBY
          end

          def spec_source
            active_code = code_for(:active)
            inactive_code = code_for(:inactive)
            rate_limit_code = code_for(:rate_limit)
            network_error_code = code_for(:network_error)
            unknown_code = code_for(:unknown)

            <<~RUBY
              # frozen_string_literal: true

              require 'spec_helper'

              # Auto-generated by ClientGenerator. Exercises the generated verifier
              # against the guardrails every partner client must satisfy.
              RSpec.describe Security::SecretDetection::PartnerTokens::#{@definition.class_name}, feature_category: :secret_detection do
                let(:client) { described_class.new }
                let(:valid_token) { #{@definition.sample_token.inspect} }
                let(:response) { instance_double(Net::HTTPResponse) }

                it_behaves_like 'a partner token client', http_method: :#{@definition.http_method}

                describe '#verify_token' do
                  #{active_code ? "context 'when the vendor reports the token active' do\n      before do\n        allow(response).to receive_messages(code: '#{active_code}', body: '{}')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'returns active' do\n        expect(client.verify_token(valid_token).active?).to be(true)\n      end\n    end" : '# no active mapping declared'}

                  #{inactive_code ? "context 'when the vendor reports the token inactive' do\n      before do\n        allow(response).to receive_messages(code: '#{inactive_code}', body: '{}')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'returns inactive' do\n        expect(client.verify_token(valid_token).inactive?).to be(true)\n      end\n    end" : '# no inactive mapping declared'}

                  #{rate_limit_code ? "context 'when the vendor rate limits the request' do\n      before do\n        allow(response).to receive_messages(code: '#{rate_limit_code}', body: '')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'raises RateLimitError' do\n        expect { client.verify_token(valid_token) }.to raise_error(described_class::RateLimitError)\n      end\n    end" : '# no rate_limit mapping declared'}

                  #{network_error_code ? "context 'when the vendor reports a service error' do\n      before do\n        allow(response).to receive_messages(code: '#{network_error_code}', body: '')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'raises NetworkError' do\n        expect { client.verify_token(valid_token) }.to raise_error(described_class::NetworkError)\n      end\n    end" : '# no network_error mapping declared'}

                  #{unknown_code ? "context 'when the vendor maps a code to unknown' do\n      before do\n        allow(response).to receive_messages(code: '#{unknown_code}', body: '')\n        allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)\n      end\n\n      it 'returns unknown' do\n        expect(client.verify_token(valid_token).unknown?).to be(true)\n      end\n    end" : '# no explicit unknown mapping declared'}

                  context 'with an unmapped response code' do
                    before do
                      allow(response).to receive_messages(code: '#{unmapped_code}', body: '')
                      allow(Integrations::Clients::HTTP).to receive(:#{@definition.http_method}).and_return(response)
                    end

                    it 'returns unknown, never inactive' do
                      result = client.verify_token(valid_token)

                      expect(result.unknown?).to be(true)
                    end
                  end

                end
              end
            RUBY
          end

          private

          # Emits case/when branches. Indentation is normalised by RuboCop
          # autocorrect after the file is written, so here we only need
          # syntactically-correct lines joined together. Codes sharing an
          # outcome collapse into one `when` list: separate branches with
          # identical bodies trip Lint/DuplicateBranch, which -a cannot fix.
          def when_branches
            @definition.compiled_status_map
              .group_by { |_code, outcome| outcome }
              # Explicitly-unknown codes fall through to else: a `when` of their
              # own would duplicate its body and trip Lint/DuplicateBranch.
              .reject { |outcome, _pairs| outcome == :unknown }
              .map do |outcome, pairs|
                codes = pairs.map(&:first).join(', ')

                "when #{codes}\n#{body_for(outcome)}"
              end
              .join("\n")
          end

          def body_for(outcome)
            case outcome
            when RATE_LIMIT
              "raise RateLimitError, \"#{double_quote_safe(@definition.partner_name)} rate limited: \#{response.code}\""
            when NETWORK_ERROR
              "raise NetworkError, \"#{double_quote_safe(@definition.partner_name)} service error: \#{response.code}\""
            else
              "token_response(:#{outcome})"
            end
          end

          # VendorDefinition already rejects quotes and backslashes in every embedded
          # field; this keeps the emission locally safe even if that gate drifts,
          # the same way API_ENDPOINT and valid_token go through #inspect.
          def double_quote_safe(str)
            str.inspect[1..-2]
          end

          def headers_literal
            case @definition.auth_style
            when 'bearer'
              "{ 'Authorization' => \"Bearer \#{token_value}\", 'Accept' => 'application/json' }"
            when 'header'
              "{ #{@definition.auth_param.inspect} => token_value, 'Accept' => 'application/json' }"
            when 'basic_username'
              # On one line this exceeds the line limit, and the rake task's rubocop -a
              # split would then break generated_client_sync_spec.rb.
              basic = '"Basic #{Base64.strict_encode64("#{token_value}:")}"'
              "{\n'Authorization' => #{basic},\n'Accept' => 'application/json'\n}"
            else
              # VendorDefinition validates auth_style, but interpolating nil here would
              # emit syntactically invalid Ruby; fail at generation time instead.
              raise ArgumentError, "unsupported auth_style: #{@definition.auth_style.inspect}"
            end
          end

          def code_for(outcome)
            @definition.compiled_status_map.find { |_code, mapped| mapped == outcome }&.first
          end

          # An HTTP code the definition does not map, used to exercise the
          # unknown-never-inactive fallthrough.
          def unmapped_code
            mapped = @definition.compiled_status_map.keys

            Rack::Utils::HTTP_STATUS_CODES.keys.find { |code| mapped.exclude?(code) }
          end
        end
      end
    end
  end
end
