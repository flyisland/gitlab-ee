# frozen_string_literal: true

module Gitlab
  module Scim
    module SchemaDefinitions
      # Core User schema limited to the attributes handled by
      # Gitlab::Scim::AttributeTransform, Gitlab::Scim::ParamsParser and
      # API::Entities::Scim::User. The read-only `groups` attribute is only
      # returned by the instance-level SCIM API.
      class User < Base
        SCHEMA_ID = 'urn:ietf:params:scim:schemas:core:2.0:User'

        class << self
          def schema_id
            SCHEMA_ID
          end

          def schema_name
            'User'
          end

          def description
            'User Account'
          end

          def attributes(context:)
            common_attributes + (context == :instance ? [groups_attribute] : [])
          end

          private

          def common_attributes
            [
              attribute('id', 'Unique identifier for the User, set from the externalId sent by the identity provider.',
                mutability: 'readOnly', returned: 'always', uniqueness: 'server'),
              attribute('externalId', 'Identifier for the User as defined by the identity provider.',
                required: true, mutability: 'writeOnly', returned: 'never'),
              attribute('userName', 'Unique identifier for the User, used as the GitLab username.',
                required: true, mutability: 'immutable', uniqueness: 'server'),
              attribute('name', 'The components of the User\'s real name.',
                type: 'complex', mutability: 'immutable', sub_attributes: name_sub_attributes),
              attribute('displayName', 'The name of the User, suitable for display to end-users.',
                mutability: 'immutable', returned: 'never'),
              attribute('emails', 'Email addresses for the User.',
                type: 'complex', multi_valued: true, required: true, mutability: 'immutable',
                sub_attributes: emails_sub_attributes),
              attribute('active', 'A Boolean value indicating the User\'s administrative status. ' \
                'Applied on update only; users are always created active.',
                type: 'boolean')
            ]
          end

          def groups_attribute
            attribute('groups', 'A list of groups to which the User belongs.',
              type: 'complex', multi_valued: true, mutability: 'readOnly', sub_attributes: groups_sub_attributes)
          end

          def groups_sub_attributes
            [
              attribute('value', 'Identifier of the Group, set from externalId or generated by GitLab.',
                mutability: 'readOnly'),
              attribute('display', 'A human-readable name of the Group.', mutability: 'readOnly'),
              attribute('type', 'A label indicating the membership type. GitLab uses "direct".',
                mutability: 'readOnly')
            ]
          end

          def name_sub_attributes
            [
              attribute('formatted', 'The full name, formatted for display.', mutability: 'immutable'),
              attribute('givenName', 'The given name of the User.', mutability: 'immutable'),
              attribute('familyName', 'The family name of the User.', mutability: 'immutable')
            ]
          end

          def emails_sub_attributes
            [
              attribute('value', 'Email address for the User.', mutability: 'immutable'),
              attribute('type', 'A label indicating the email\'s function. GitLab uses "work".',
                mutability: 'immutable'),
              attribute('primary', 'A Boolean value indicating the preferred email address.',
                type: 'boolean', mutability: 'immutable')
            ]
          end
        end
      end
    end
  end
end
