# frozen_string_literal: true

module Gitlab
  module Scim
    module SchemaDefinitions
      # Core Group schema limited to the attributes handled by
      # API::Entities::Scim::Group. Only the instance-level SCIM API
      # exposes a /Groups resource.
      class Group < Base
        SCHEMA_ID = 'urn:ietf:params:scim:schemas:core:2.0:Group'

        class << self
          def schema_id
            SCHEMA_ID
          end

          def schema_name
            'Group'
          end

          def description
            'Group'
          end

          def attributes(**)
            [
              attribute('id', 'Unique identifier for the Group, set from externalId or generated by GitLab.',
                mutability: 'readOnly', returned: 'always', uniqueness: 'server'),
              attribute('displayName', 'A human-readable name for the Group.',
                required: true, mutability: 'immutable'),
              attribute('members', 'A list of members of the Group.',
                type: 'complex', multi_valued: true, sub_attributes: members_sub_attributes)
            ]
          end

          private

          def members_sub_attributes
            [
              attribute('value', 'Identifier of the member of this Group.',
                mutability: 'immutable'),
              attribute('display', 'A human-readable name of the member.', mutability: 'readOnly'),
              attribute('type', 'A label indicating the type of resource. GitLab uses "User".',
                mutability: 'immutable')
            ]
          end
        end
      end
    end
  end
end
