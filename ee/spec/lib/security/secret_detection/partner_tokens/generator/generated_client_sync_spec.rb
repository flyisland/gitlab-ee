# frozen_string_literal: true

require 'fast_spec_helper'

# Keeps the committed vendor definitions and their generated clients in sync:
# every YAML under generator/definitions/ is regenerated here and compared to
# the checked-in files, so a definition edit without regeneration fails CI.
RSpec.describe 'Generated validity check client sync', feature_category: :secret_detection do
  definitions_dir = Rails.root.join('ee/lib/security/secret_detection/partner_tokens/generator/definitions')
  definition_paths = Dir.glob(definitions_dir.join('*.{yml,yaml}'))

  # PoC-generated before this generator landed; they carry the auto-generated
  # header but have no committed definition until they are regenerated.
  legacy_poc_clients = %w[datadog_client.rb heroku_client.rb sendgrid_client.rb].freeze

  # The generate task runs rubocop -a on the written files, which normalises
  # layout but never content, so the comparison ignores indentation.
  def significant_lines(source)
    source.lines.map(&:strip).reject(&:empty?)
  end

  def committed_source(path)
    File.read(Rails.root.join(path))
  end

  def definition_for(path)
    Security::SecretDetection::PartnerTokens::Generator::VendorDefinition.new(YAML.safe_load_file(path))
  end

  definition_paths.each do |path|
    context "with #{File.basename(path)}" do
      let(:generator) do
        Security::SecretDetection::PartnerTokens::Generator::ClientGenerator.new(definition_for(path))
      end

      it 'matches the checked-in client' do
        expect(significant_lines(committed_source(generator.client_path)))
          .to eq(significant_lines(generator.client_source))
      end

      it 'matches the checked-in client spec' do
        expect(significant_lines(committed_source(generator.spec_path)))
          .to eq(significant_lines(generator.spec_source))
      end
    end
  end

  it 'has a committed definition for every generated client' do
    client_dir = Rails.root.join('ee/lib/security/secret_detection/partner_tokens/*.rb')

    generated_basenames = Dir.glob(client_dir).filter_map do |file|
      File.basename(file) if File.read(file).include?('Auto-generated by ClientGenerator')
    end

    known_basenames = definition_paths.map do |path|
      generator = Security::SecretDetection::PartnerTokens::Generator::ClientGenerator.new(definition_for(path))

      File.basename(generator.client_path)
    end

    unaccounted = generated_basenames - known_basenames - legacy_poc_clients

    expect(unaccounted).to be_empty,
      "Generated clients without a committed definition under generator/definitions/: #{unaccounted.join(', ')}"
  end
end
